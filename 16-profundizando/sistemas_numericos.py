# Profundizando Sistemas de Numeracion
# Decimal
a = 10

#Binario
a = 0b1010

#Octal
a = 0o12

#Hexadecimal
a = 0xA

# Convertir un tipo entero pero incluyendo la base 
# base decimal
a = int("23", 10)
# base binario 
a = int("10111", 2)
# Base octal
a = int("27", 8)
# Base hexadecimal
a = int("17", 16)
# Base 5
a = int("344", 5)
print(f"a:{a}")
