# Variables en python

# Declaracion 
edad = 28
altura = 1.65
pais = "Argentina"

# Acceder a las variables
print("Valores iniciales: ")
print("Edad:", edad)
print("Altura:", altura)
print("Pais:", pais)

# Modificar el valor de una variable
edad = 24
altura = 1.70
pais = "Andorra"

print("Valores modificados: ")
print("Edad:", edad)
print("Altura:", altura)
print("Pais:", pais)

# En python el tipo es dinamico
edad = "treinta"
print("Edad en texto:", edad)


# Si queremos acceder a una variable no declarada
telefono = 234576
print("telefono: ", telefono)