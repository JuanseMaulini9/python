# Metodos cadenas
cadena1 = "Hola mundo"
print(f"cadena original: {cadena1}")
mayusculas = cadena1.upper()
print(f"cadena en mayusculas: {mayusculas}")
print(f"cadena en minusculas: {cadena1.lower()}" ) # Convertir a minusculas
cadena2 = "  Junase maulini  "
print(f"cadena con espacion {cadena2}")
print(f"Cadena sin espacion: {cadena2.strip()}")