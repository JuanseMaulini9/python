# Operadores aritmeticos

a = 10
b = 3

# Suma
suma = a + b
print(f"suma: {suma}")

# Resta
resta = a - b
print(f"resta: {resta}")

# multiplicacion
multiplicacion = a * b
print(f"multiplicacion: {multiplicacion}")

# division
division = a / b
print(f"division: {division:.2f}")

# division entera
division_entera = a // b
print(f"division entera: {division_entera}")

# modulo
modulo = a % b
print(f"modulo: {modulo}")

# Exponente
exponente = a ** b
print(f"exponente: {exponente}")

