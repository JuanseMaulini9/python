# Operadores de comparacion
a, b = 7, 5
print(f"Valor inicial a: {a}, b: {b}")

# Operador igualdad ==
resultado = (a == b)
print(f"Resultado de evaluar a == b es: {resultado}")

# Operador diferente !=
resultado = (a != b)
print(f"Resultado de evaluar a != b es: {resultado}")

# Operador mayor que >
resultado = (a > b)
print(f"Resultado de evaluar a > b es: {resultado}")

# Operador mayor que >=
resultado = (a >= b)
print(f"Resultado de evaluar a >= b es: {resultado}")

# Operador mayor que <
resultado = (a < b)
print(f"Resultado de evaluar a < b es: {resultado}")

# Operador mayor que <=
resultado = (a <= b)
print(f"Resultado de evaluar a <= b es: {resultado}")